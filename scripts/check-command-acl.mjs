import fs from "node:fs";
import path from "node:path";

// Tauri rejects an invoke whose command is missing from the window capability, so the
// authoritative command list in app_commands.rs and the allow-* entries in
// capabilities/default.json have to stay in lockstep. Drift only shows up as a runtime
// "not allowed" error in a packaged build, which no unit test reaches.
// The browser-dev WS bridge reimplements dispatch manually and must cover every app command.
// Bridge-only extras (browser_e2e_*, dev lifecycle) are allowed.
const root = process.cwd();
const commandsPath = path.join(root, "src-tauri", "app_commands.rs");
const capabilityPath = path.join(root, "src-tauri", "capabilities", "default.json");
const bridgePath = path.join(root, "src-tauri", "src", "browser_dev.rs");
const permissionsPath = path.join(root, "src-tauri", "permissions", "autogenerated");

const commandsSource = fs.readFileSync(commandsPath, "utf8");
const callbackBody = commandsSource.slice(commandsSource.indexOf("$callback!("));
const commands = [...callbackBody.matchAll(/^\s+([a-z][a-z0-9_]*),\s*$/gmu)].map(([, name]) => name);

if (!commands.length) {
  console.error(`No commands found in ${path.relative(root, commandsPath)}.`);
  process.exit(1);
}

const capability = JSON.parse(fs.readFileSync(capabilityPath, "utf8"));
// Plugin permissions ("core:window:allow-set-theme") are namespaced; app commands are not.
const granted = new Set(
  capability.permissions
    .filter((permission) => typeof permission === "string" && permission.startsWith("allow-"))
    .map((permission) => permission.slice("allow-".length).replaceAll("-", "_"))
);

const bridgeSource = fs.readFileSync(bridgePath, "utf8");
const bridged = new Set([...bridgeSource.matchAll(/"([a-z][a-z0-9_]*)"\s*=>/gu)].map(([, name]) => name));

const missing = commands.filter((command) => !granted.has(command));
const stale = [...granted].filter((command) => !commands.includes(command));
const unbridged = commands.filter((command) => !bridged.has(command));

// tauri-build writes one permissions/autogenerated/<command>.toml per entry of the
// authoritative list, but it only ever adds: retiring a command used to leave its file
// behind forever, advertising an `allow-<retired>` identifier nothing backs. `build.rs`
// now prunes those, so a leftover here means the tree has not been rebuilt since the
// command was retired — or that something outside the generator wrote into the directory.
// The whole directory is gitignored build output; a fresh clone has none of it yet, which
// is not drift.
const retired = [];
if (fs.existsSync(permissionsPath)) {
  const known = new Set(commands);
  for (const entry of fs.readdirSync(permissionsPath)) {
    if (!entry.endsWith(".toml")) continue;
    const command = entry.slice(0, -".toml".length);
    if (!known.has(command)) retired.push(entry);
  }
}

if (missing.length || stale.length || unbridged.length || retired.length) {
  const capabilityName = path.relative(root, capabilityPath);
  const bridgeName = path.relative(root, bridgePath);
  missing.forEach((command) => {
    console.error(`${capabilityName}: missing "allow-${command.replaceAll("_", "-")}" for command ${command}`);
  });
  stale.forEach((command) => {
    console.error(`${capabilityName}: "allow-${command.replaceAll("_", "-")}" has no matching command`);
  });
  unbridged.forEach((command) => {
    console.error(`${bridgeName}: no dispatch arm for command ${command}`);
  });
  const permissionsName = path.relative(root, permissionsPath);
  retired.forEach((entry) => {
    console.error(`${permissionsName}/${entry}: 已退役命令的权限文件残留，重建一次即可清除`);
  });
  process.exitCode = 1;
} else {
  console.log(`Command ACL audit passed: ${commands.length} commands granted and bridged.`);
}
